export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>("ar");
  const [isHydrated, setIsHydrated] = useState(false);

  // Restore the saved preference before writing anything back to storage.
  // This prevents the initial Arabic default from overwriting a saved English choice.
  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(LANGUAGE_KEY);
      if (saved === "ar" || saved === "en") setLanguage(saved);
    } catch {
      // Storage can be unavailable in private or restricted browser contexts.
    } finally {
      setIsHydrated(true);
    }
  }, []);

  useEffect(() => {
    if (!isHydrated) return;
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    try {
      window.localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      // Keep the current in-memory language even if storage is unavailable.
    }
  }, [language, isHydrated]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      toggleLanguage: () => setLanguage((current) => current === "ar" ? "en" : "ar"),
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

export function LanguageSwitcher() {
  const { language, toggleLanguage } = useLanguage();
  return (
    <button
      type="button"
      onClick={toggleLanguage}
      aria-label={language === "ar" ? "Switch language to English" : "تغيير اللغة إلى العربية"}
      title={language === "ar" ? "English" : "العربية"}
      className="ho-language-switcher"
    >
      <span aria-hidden="true">文</span>
      {language === "ar" ? "English" : "العربية"}
    </button>
  );
}
