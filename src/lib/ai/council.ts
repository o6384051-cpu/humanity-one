export function buildCouncilPanelPrompt(goal: string, memory: string): string {
  return [
    "أنت مجلس خبراء HUMANITY ONE. حلّل الهدف من جميع التخصصات المذكورة.",
    AI_COUNCIL_POLICY,
    `الهدف: ${goal}`,
    `المعرفة المؤسسية المتاحة:\n${memory}`,
    "أخرج رأي كل تخصص بإيجاز، نقاط الاتفاق، الخلافات والمخاطر، ثم توصية مشتركة قابلة للتنفيذ.",
    "لا تدّع استخدام مصادر أو أدوات لم تستخدمها.",
  ].join("\n\n");
}

export function buildCouncilReviewPrompt(goal: string, panelResult: string): string {
  return [
    "أنت المراجع النهائي لمجلس HUMANITY ONE. راجع مخرجات المجلس بصرامة.",
    AI_COUNCIL_POLICY,
    `الهدف الأصلي: ${goal}`,
    `مخرجات المجلس:\n${panelResult}`,
    "تحقق من التناقضات والافتراضات والتكاليف والآثار الإنسانية. لا تضف حقائق غير مدعومة. قدّم جوابًا نهائيًا واحدًا واضحًا.",
  ].join("\n\n");
}
